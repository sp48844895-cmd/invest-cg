        <p class="ecosystem-kicker">Innovation On Campus</p>
        <h3><i class="fa-solid fa-lightbulb"></i> College Innovation Startup Cells (CISC)</h3>
    </div>
    <p>
        Each eligible College Innovation Startup Cell (CISC) shall be provided with operational support of up to ₹5
        lakhs per year, aimed at facilitating activities such as ideation, prototyping, mentoring, startup outreach, and
        innovation challenges.
    </p>

    <h4><i class="fa-solid fa-clipboard-check"></i> Eligibility Criteria</h4>
    <ul class="ecosystem-list">
        <li>The CISC must be established within a state/central Government affiliate or recognized educational institutes (Higher/Technical) located in Chhattisgarh.</li>
        <li>The institution must have a functional innovation or entrepreneurship development cell or demonstrate commitment to startup promotion through prior activities.</li>
        <li>The CISC must submit a yearly action plan outlining proposed activities, budget utilization, and expected outcomes.</li>
        <li>The institution must commit to matching the operational support through its own resources or partnerships.</li>
        <li>The CISC must maintain records of student participation, startup outcomes, and submit biannual progress reports to the Implementing Agency.</li>
    </ul>

