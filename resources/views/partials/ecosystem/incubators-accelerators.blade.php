        <div class="ecosystem-card stack-card">
            <h4><i class="fa-solid fa-landmark"></i> Government Incubator</h4>
            <div class="ecosystem-tier">
                <h5><i class="fa-solid fa-award"></i> Tier 1 Government Incubator</h5>
                <p>
                    Capital Grant assistance to new incubators covering 100% of the project cost (excluding expenses
                    related to land and building), up to a maximum of ₹ 10 crores for new facility. Within this, the
                    maximum limit for capital expenditure (Capex) will be 40%. The eligible operational expenditure
                    (Opex) will be distributed over a period of 5 years and released annually.
                </p>
                <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria</h6>
                <ol class="ecosystem-ordered">
                    <li>The proposed incubator must be registered as a legal entity in accordance with Clause 7.3 of this policy</li>
                    <li>The proposed incubator must have a minimum of 3 years of operational experience and should have conducted at least 3 incubation cohorts.</li>
                    <li>It must have functioned as an incubator/accelerator for a minimum of 30 incubates and should have facilitated funding support to at least 4 startup units</li>
                    <li>The proposed incubator shall be required to establish a formal collaboration or partnership with another incubator that meets the above-mentioned eligibility criteria.</li>
                </ol>
                <p class="ecosystem-note">
                    The proposed incubator must have identified a minimum built-up area of 10,000 square feet within the state, with adequate facilities to accommodate at least 25 incubates.
                </p>
            </div>
            <div class="ecosystem-tier">
                <h5><i class="fa-solid fa-medal"></i> Tier 2 Government Incubator</h5>
                <p>
                    The proposed incubators will be provided a grant of 100% of their project cost, subject to a maximum
                    limit of ₹6 crore. Within this, the maximum limit for capital expenditure (Capex) will be 40%. The
                    eligible operational expenditure (Opex) will be distributed over a period of 5 years and released
                    annually.
                </p>
                <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria</h6>
                <ol class="ecosystem-ordered">
                    <li>The proposed incubator must be registered as a legal entity in accordance with Clause 7.3 of this policy</li>
                    <li>The incubator must have a minimum of 3 years of operational experience and should have</li>
                    <li>conducted at least 3 incubation cohorts.</li>
                    <li>The incubator must have functioned as an incubator/accelerator for a minimum of 30 incubates and should have facilitated funding support to at least 2 startup units</li>
                    <li>The proposed incubator shall be required to establish a formal collaboration or partnership with another incubator that meets the above-mentioned eligibility criteria.</li>
                </ol>
                <p class="ecosystem-note">
                    The proposed incubator must have identified a minimum built -up area of 5,000 square feet within the state, with adequate facilities to accommodate at least 15 incubates.
                </p>
            </div>
            <div class="ecosystem-tier">
                <h5><i class="fa-solid fa-arrow-trend-up"></i> Upgradation Package</h5>
                <p>
                    Incubators established in the state will be eligible for the grant mentioned in Clause 9.2 of the
                    policy if they increase their approved fixed capital investment by a minimum of 25% and increase
                    their incubation capacity (number of seats) by 25%.
                </p>
                <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria</h6>
                <ol class="ecosystem-ordered">
                    <li>The incubator shall comply with the definition prescribed under Clause 7.3 of this Policy, or as may be amended from time to time by the competent authority</li>
                    <li>The incubator should be operational for at least 2 years on the date of application under the policy</li>
                    <li>The incubator shall possess a minimum seating capacity to accommodate at least twenty incubates and must be physically incubating minimum five startup entities at the time of submission of the application</li>
                    <li>The incubator shall have duly audited annual financial statements for the preceding financial years</li>
                    <li>Must employ a qualified dedicated team responsible for providing mentorship, technical and business support to startups</li>
                    <li>The incubator must have supported by the Central/State Government(s) under any scheme</li>
                    <li>Any additional criteria may be decided by the SSPC or Nodal Department</li>
                </ol>
            </div>
            <div class="ecosystem-tier">
                <h5><i class="fa-solid fa-calendar-star"></i> Event Organization Assistance</h5>
                <p>
                    Recognized incubators based in Chhattisgarh shall be eligible for financial assistance of ₹1 lakh per
                    event for organizing state-level programs related to startups, innovation, and entrepreneurship. The
                    support is subject to a maximum annual limit of ₹4 lakhs per incubator, and the assistance provided
                    shall not exceed the actual contribution made by the incubator towards the event.
                </p>
