    <div class="policy-intro">
        <div class="policy-lead">
            <p>
                The state provides support to startups at different stages of life cycle. Sector agnostic schemes such
                as, Student Start-up and Innovation Policy provides support to start-ups at idea stage, whereas
                Chhattisgarh Innovation and Startup Promotion Policy aims for assistance for Startups/ Innovation
                provides support to start-ups at seed funding and scale up stage.
            </p>
            <p>
                Through this policy, the state envisions empowering its youth, harnessing local talent, and encouraging
                risk-taking and innovation at every level. By fostering collaboration between academia, industry,
                investors, and government agencies, Chhattisgarh aims to cultivate a self-sustaining startup ecosystem
                that generates employment, boosts competitiveness, and contributes to the vision of “Atmanirbhar
                Bharat”.
            </p>
            <p>
                This Startup Policy thus serves as a cornerstone for Chhattisgarh’s journey towards becoming a
                knowledge-driven, innovation-led economy, ensuring that entrepreneurial spirit thrives at the grassroots
                and transforms the state into a powerhouse of ideas, enterprises, and opportunities.
            </p>
        </div>
    </div>

