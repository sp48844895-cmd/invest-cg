    <div class="eligibility-card">
        <h4><i class="fa-solid fa-clipboard-check"></i> Eligibility Criteria:</h4>
        <ul class="ecosystem-list ecosystem-list-cisc">
            <li>
                <i class="fa-solid fa-check-circle"></i>
                <span>The CISC must be established within a state/central Government affiliate or recognized educational institutes (Higher/Technical) located in Chhattisgarh.</span>
            </li>
            <li>
                <i class="fa-solid fa-check-circle"></i>
                <span>The institution must have a functional innovation or entrepreneurship development cell or demonstrate commitment to startup promotion through prior activities.</span>
            </li>
            <li>
                <i class="fa-solid fa-check-circle"></i>
                <span>The CISC must submit a yearly action plan outlining proposed activities, budget utilization, and expected outcomes.</span>
            </li>
            <li>
                <i class="fa-solid fa-check-circle"></i>
                <span>The institution must commit to matching the operational support through its own resources or partnerships.</span>
            </li>
            <li>
                <i class="fa-solid fa-check-circle"></i>
                <span>The CISC must maintain records of student participation, startup outcomes, and submit biannual progress reports to the Implementing Agency.</span>
            </li>
        </ul>
    </div>

