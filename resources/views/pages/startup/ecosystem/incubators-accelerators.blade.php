            <div class="ecosystem-tier ecosystem-tier-enhanced">
                <div class="tier-badge tier-badge-gold">
                    <i class="fa-solid fa-award"></i>
                    <span>Tier 1</span>
                </div>
                <h5>Tier 1 Government Incubator</h5>
                <p>
                    The proposed new government incubator shall be provided a grant of 75% of their project cost, out of which the maximum limit for capital expenditure (Capex) shall be 40%. The eligible operational expenditure shall be distributed over a period of five years and released on an annual basis.
                </p>
                <div class="eligibility-box">
                    <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria:</h6>
                    <ol class="ecosystem-ordered">
                        <li>The proposed incubator must be registered as a legal entity in accordance with Clause 5. (2) (i) of this Chhattisgarh Innovation and Startup Promotion Policy</li>
                        <li>The proposed incubator must have a minimum of 3 years of operational experience and should have conducted at least 3 incubation cohorts.</li>
                        <li>It must have functioned as an incubator/accelerator for a minimum of 30 incubates and should have facilitated funding support to at least 4 startup units<br><strong>Or</strong> <br>
                        The proposed incubator shall be required to establish a formal collaboration or partnership with another incubator that meets the above-mentioned eligibility criteria.
                    </li>
                        

                        <li>The proposed incubator must have identified a minimum built-up area of 10,000 square feet within the state, with adequate facilities to accommodate at least 25 incubates.</li>
                    </ol>
                </div>
            </div>
            
            <div class="ecosystem-tier ecosystem-tier-enhanced">
                <div class="tier-badge tier-badge-silver">
                    <i class="fa-solid fa-medal"></i>
                    <span>Tier 2</span>
                </div>
                <h5>Tier 2 Government Incubator</h5>
                <p>
                    The Proposed incubators shall be provided a grant equivalent to 75% of their project cost, with the maximum limit for capital expenditure (Capex) capped at 40%. The eligible operational expenditure shall be spread over a period of five years and disbursed on an annual basis.
                </p>
                <div class="eligibility-box">
                    <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria:</h6>
                    <ol class="ecosystem-ordered">
                        <li>The proposed incubator must be registered as a legal entity in accordance with Clause 5.(2) (i) of this policy</li>
                        <li>The incubator must have a minimum of 3 years of operational experience and should have conducted at least 3 incubation cohorts.</li>
                        <li>The incubator must have functioned as an incubator/accelerator for a minimum of 30 incubates and should have facilitated funding support to at least 2 startup units<br><strong>Or</strong> <br>
                           The proposed incubator shall be required to establish a formal collaboration or partnership with another incubator that meets the above-mentioned eligibility criteria.
                    </li>
                     
                        <li>The proposed incubator must have identified a minimum built-up area of 5,000 square feet within the state, with adequate facilities to accommodate at least 15 incubates</li>
                    </ol>
                </div>
            </div>
            
            <div class="ecosystem-tier ecosystem-tier-enhanced">
                <div class="tier-badge tier-badge-upgrade">
                    <i class="fa-solid fa-arrow-trend-up"></i>
                    <span>Upgrade</span>
                </div>
                <h5>Upgradation Package</h5>
                <p>
                    Incubators established in the state will be eligible for the grant mentioned in Clause 972 of the policy if they increase their approved fixed capital investment by a minimum of 25% and increase their incubation capacity (number of seats) by 25%.
                </p>
                <div class="eligibility-box">
                    <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria:</h6>
                    <ol class="ecosystem-ordered">
                        <li>Must be an incubator as defined under Clause 5.(2)(i) of the policy.</li>
                        <li>Must have a minimum of 2 years of operational experience at the time of application.</li>
                        <li>The incubation center must have a seating capacity for at least 20 incubates and should have provided incubation to a minimum of 5 startup units.</li>
                        <li>Audited annual financial statements for previous financial years.</li>
                        <li>A qualified team must be available for mentorship, technical, and business support.</li>
                        <li>The incubation center must be a recognized incubator under any scheme of the Central/State.</li>
                        <br>
                        Any additional criteria may be decided by the Nodal Department
                    </ol>
                </div>
            </div>
            
            <div class="ecosystem-tier ecosystem-tier-enhanced">
                <div class="tier-badge tier-badge-event">
                    <i class="fa-solid fa-calendar"></i>
                    <span>Event</span>
                </div>
                <h5>Event Organization Assistance</h5>
                <p>
                    Recognized incubators based in Chhattisgarh shall be eligible for financial assistance of ₹1 lakh per
                    event for organizing state -level programs related to startups, innovation, and entrepreneurship. This support is subject to a maximum annual limit of ₹4 lakhs per incubator, and the assistance provided
                    shall not exceed the actual contribution made by the incubator towards the event.
                </p>
             
            </div>
