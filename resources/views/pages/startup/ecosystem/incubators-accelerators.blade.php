                <h5>Tier 1 Private Incubator</h5>
                <p>
                    The proposed incubators will be provided a grant of 50% of their project cost, subject to a maximum limit of ₹3 crore. Within this, the maximum limit for capital expenditure (Capex) will be 40%. The eligible operational expenditure (Opex) will be distributed over a period of 5 years and disbursed on an annual basis.
                </p>
                <div class="eligibility-box">
                    <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria:</h6>
                    <ol class="ecosystem-ordered">
                        <li>The proposed incubator must be registered as a legal entity in accordance with Clause 5.(2) (i) of this policy</li>
                        <li>The proposed incubator must have a minimum of 3 years of operational experience as an incubator.</li>
                        <li>The proposed incubator must have conducted at least 5 incubation cohorts and must have worked as an incubator for a minimum of 50 incubates and as an accelerator for at least 10 startups.</li>
                        <li>The incubator must have facilitated funding support for at least 5 startups in last 3 years through government schemes, angel funds, or venture capital<br><strong>Or</strong> <br>
                        The proposed incubator shall be required to establish a formal collaboration or partnership with another incubator that meets the above-mentioned eligibility criteria.
                    </li>
                    
                        <li>The proposed incubator must have identified a minimum built-up area of 10,000 square feet within the state, with adequate facilities to accommodate at least 25 incubates.</li>
                    </ol>
                </div>
