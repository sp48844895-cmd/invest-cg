                    <span>Accelerate</span>
                </div>
                <h5>Acceleration Program Assistance</h5>
                <p>
                    Incubation centers will be given reimbursement of expenses up to a maximum of ₹15 lakh for the event if they provide support to startups in the development phase through incubation centers, for organizing an acceleration program (cohort) for a minimum duration of 8 weeks.
                </p>
                <div class="eligibility-box">
                    <h6><i class="fa-solid fa-list-check"></i> Eligibility Criteria:</h6>
                    <ol class="ecosystem-ordered">
                        <li>For this purpose, incubation centers must obtain prior approval from the nodal department, and the funds will be distributed only based on actual expenditure and achievement of approved targets.</li>
                        <li>Only incubators recognized by the state government will be eligible for this grant.</li>
                        <li>The proposed program must be at least 8 weeks long, include a minimum of 10 development stage startups, have a fixed curriculum, and have defined outcomes.</li>
                    </ol>
