                        <li>The incubator must have a minimum of 3 years of operational experience as an incubator.</li>
                        <li>The incubator must have conducted at least 3 incubation cohorts and must have worked with 30 incubates as an incubator.</li>
                        <li>The Incubator must have supported at least 2 startups in securing investments through government schemes, angel funds, or venture capital in the past three years<br><strong>or</strong> <br>
                         The proposed incubator shall be required to establish a formal collaboration or partnership with another incubator that meets the above-mentioned eligibility criteria.
                    </li>
                    <li>
 The proposed incubator must have identified a minimum built-up area of 5,000 square feet within the state, with adequate facilities to accommodate at least 15 incubates. The proposed incubator must be registered as a legal entity in accordance with Clause 7.3 of this policy
